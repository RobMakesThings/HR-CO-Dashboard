"""Idempotently provision the DASHBOARD auth schema (user + table) and seed users.

Run from backend/:  python -m seed.provision_dashboard
Uses SYSTEM credentials from env (ORACLE_SYSTEM_PASSWORD) to create the user,
then connects as dashboard to create the table + index. Requires the dashboard
user's password (ORACLE_DASH_PASSWORD).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import oracledb

from app.config import settings
from app.security import hash_password

SYSTEM_PASSWORD = os.environ.get("ORACLE_SYSTEM_PASSWORD", "letmein")
DASH_PASSWORD = settings.oracle_dash_password
ADMIN_PASSWORD = os.environ.get("DASH_ADMIN_PASSWORD", "admin123")
VIEWER_PASSWORD = os.environ.get("DASH_USER_PASSWORD", "user123")


def _connect(user: str, password: str) -> oracledb.Connection:
    return oracledb.connect(user=user, password=password, dsn=settings.oracle_dsn)


def create_user_if_missing():
    s = _connect("SYSTEM", SYSTEM_PASSWORD)
    cur = s.cursor()
    cur.execute("SELECT COUNT(*) FROM all_users WHERE username = 'DASHBOARD'")
    if cur.fetchone()[0] == 0:
        cur.execute(f"CREATE USER dashboard IDENTIFIED BY {DASH_PASSWORD}")
        print("created dashboard user")
    for g in ["CONNECT", "RESOURCE", "CREATE SESSION"]:
        cur.execute(f"GRANT {g} TO dashboard")
    try:
        cur.execute("ALTER USER dashboard QUOTA UNLIMITED ON USERS")
        print("granted unlimited quota on USERS")
    except Exception as e:
        print("quota: ", str(e)[:60])
    s.commit()
    s.close()


def create_table_if_missing():
    d = _connect("dashboard", DASH_PASSWORD)
    c = d.cursor()
    c.execute("SELECT COUNT(*) FROM user_tables WHERE table_name = 'APP_USERS'")
    if c.fetchone()[0] == 0:
        c.execute(
            """
            CREATE TABLE app_users (
              app_user_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              username      VARCHAR2(50)  NOT NULL UNIQUE,
              password_hash VARCHAR2(255) NOT NULL,
              role          VARCHAR2(20)  NOT NULL CHECK (role IN ('admin','viewer')),
              created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """
        )
        # username has a UNIQUE constraint; Oracle auto-indexes it (this also
        # covers login lookups), so no separate index is needed.
        print("created app_users table")
    d.commit()
    d.close()


def seed_users():
    d = _connect("dashboard", DASH_PASSWORD)
    c = d.cursor()
    users = [("admin", ADMIN_PASSWORD, "admin"), ("user", VIEWER_PASSWORD, "viewer")]
    for username, pw, role in users:
        c.execute("SELECT app_user_id FROM app_users WHERE username = :1", (username,))
        hashed = hash_password(pw)
        if c.fetchone():
            c.execute(
                "UPDATE app_users SET password_hash = :1, role = :2 WHERE username = :3",
                (hashed, role, username),
            )
        else:
            c.execute(
                "INSERT INTO app_users (username, password_hash, role) VALUES (:1, :2, :3)",
                (username, hashed, role),
            )
        print(f"seeded {username} ({role})")
    d.commit()
    d.close()


def main():
    create_user_if_missing()
    create_table_if_missing()
    seed_users()
    print("PROVISIONING_COMPLETE")


if __name__ == "__main__":
    main()
